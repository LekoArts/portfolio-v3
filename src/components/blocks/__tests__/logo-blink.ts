const numbers = (d: string): number[] => d.match(/-?\d*\.?\d+/g)!.map(Number)

describe('logoPath', () => {
	it('draws the original logo when the eyes are open', () => {
		const actual = numbers(logoPath())
		const expected = numbers(ORIGINAL_LOGO)
		expect(actual).toHaveLength(expected.length)
		actual.forEach((n, i) => expect(n).toBeCloseTo(expected[i], 3))
	})
})

describe('eyesAt', () => {
	it('starts and ends with open eyes', () => {
		expect(logoPath(eyesAt(0).left, eyesAt(0).right)).toBe(logoPath())
		const end = eyesAt(BLINK_DURATION)
		expect(logoPath(end.left, end.right)).toBe(logoPath())
	})

	it('closes both eyes during the blink', () => {
		const { left, right } = eyesAt(300)
		// Inner corners of upper and lower lid nearly touch
		expect(left[6][1] - left[0][1]).toBeLessThan(1.5)
		expect(right[6][1] - right[0][1]).toBeLessThan(1.5)
	})

	it('never lets the upper lid cross below the lower lid', () => {
		for (let t = 0; t <= BLINK_DURATION; t++) {
			for (const eye of Object.values(eyesAt(t)))
				expect(eye[0][1]).toBeLessThanOrEqual(eye[6][1])
		}
	})
})
